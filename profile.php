 * Account page - username, password, and job-reminder preferences.
 * Name/contact/photo, header colours, accent colour, and CV visibility are edited
 * in the content editor (Profile / Appearance / Visibility sections).
 */

require_once __DIR__ . '/php/helpers.php';

requireAuth();

$userId = getUserId();
$error = getFlash('error');
$success = getFlash('success');
$passwordError = getFlash('password_error');
$passwordSuccess = getFlash('password_success');

// Get profile data
$profile = db()->fetchOne(
    "SELECT * FROM profiles WHERE id = ?",
    [$userId]
);

// Check if username is auto-generated (starts with "user" followed by 8 alphanumeric chars)
$isAutoGeneratedUsername = preg_match('/^user[a-z0-9]{8}$/i', $profile['username'] ?? '');

// Subscription summary (read-only here; upgrade/cancel/billing all happen on /subscription.php)
$subscriptionContext = getUserSubscriptionContext($userId);
$expiryInfo = formatSubscriptionExpiry($subscriptionContext);

// Handle form submission
if (isPost()) {
    // Password change (separate from main account form)
    if (post('profile_action') === 'change_password') {
        if (!verifyCsrfToken(post(CSRF_TOKEN_NAME))) {
            setFlash('password_error', 'Invalid security token. Please try again.');
            redirect('/profile.php?tab=password');
        }
        $currentPassword = post('current_password', '');
        $newPassword = post('new_password', '');
        $confirmPassword = post('confirm_password', '');
        if ($newPassword !== $confirmPassword) {
            setFlash('password_error', 'New passwords do not match.');
            redirect('/profile.php?tab=password');
        }
        $result = changePasswordForUser($userId, $currentPassword, $newPassword);
        if ($result['success']) {
            setFlash('password_success', 'Your password has been updated successfully.');
            redirect('/profile.php?tab=password');
        }
        setFlash('password_error', $result['error']);
        redirect('/profile.php?tab=password');
    }

    // Verify CSRF token (main account form)
    $token = post(CSRF_TOKEN_NAME);
    if (!verifyCsrfToken($token)) {
        setFlash('error', 'Invalid security token. Please try again.');
        redirect('/profile.php');
    }

    $data = [];

    // Username is required, so we must have it
    $username = trim(post('username', ''));
    if ($username === '') {
        setFlash('error', 'Username is required');
        redirect('/profile.php');
    }
    $data['username'] = strip_tags($username);

    if (!preg_match('/^[a-z0-9][a-z0-9\-_]+$/', $data['username'])) {
        setFlash('error', 'Username can only contain lowercase letters, numbers, hyphens, and underscores');
        redirect('/profile.php');
    }

    // Check if username is already taken by another user
    $existing = db()->fetchOne(
        "SELECT id FROM profiles WHERE username = ? AND id != ?",
        [$data['username'], $userId]
    );

    if ($existing) {
        setFlash('error', 'Username is already taken');
        redirect('/profile.php');
    }

    if (checkForXss($data['username'])) {
        setFlash('error', 'Invalid content in username');
        redirect('/profile.php');
    }

    // Closing date reminder preferences (only if migration has run)
    if (array_key_exists('closing_date_reminder_enabled', $profile)) {
        $data['closing_date_reminder_enabled'] = (post('closing_date_reminder_enabled') === '1' || post('closing_date_reminder_enabled') === 'on') ? 1 : 0;
        $customDays = array_filter(array_map('intval', preg_split('/[\s,]+/', trim(post('closing_date_reminder_days_custom', '')), -1, PREG_SPLIT_NO_EMPTY)));
        $presetDays = [];
        if (post('remind_14') === '1' || post('remind_14') === 'on') $presetDays[] = 14;
        if (post('remind_7') === '1' || post('remind_7') === 'on') $presetDays[] = 7;
        if (post('remind_3') === '1' || post('remind_3') === 'on') $presetDays[] = 3;
        if (post('remind_1') === '1' || post('remind_1') === 'on') $presetDays[] = 1;
        $allDays = array_unique(array_merge($presetDays, $customDays));
        sort($allDays, SORT_NUMERIC);
        $data['closing_date_reminder_days'] = implode(',', $allDays) ?: '7,3,1';
    }

    $data['updated_at'] = date('Y-m-d H:i:s');

    // Update profile
    try {
        db()->update('profiles', $data, 'id = ?', [$userId]);
        setFlash('success', 'Account updated successfully');
        redirect('/profile.php');
    } catch (PDOException $e) {
        error_log("Profile update error: " . $e->getMessage());
        error_log("SQL State: " . $e->getCode());
        error_log("User ID: " . $userId);
        error_log("Data being updated: " . print_r($data, true));

        $errorMessage = 'Failed to update account. ';

        if ($e->getCode() == 23000) { // Integrity constraint violation
            if (strpos($e->getMessage(), 'username') !== false) {
                $errorMessage .= 'Username is already taken or invalid format.';
            } else {
                $errorMessage .= 'A database constraint was violated.';
            }
        } elseif (DEBUG || defined('SHOW_ERRORS') && SHOW_ERRORS) {
            $errorMessage .= 'Error: ' . $e->getMessage() . ' (Code: ' . $e->getCode() . ')';
        } else {
            $errorMessage .= 'Please try again. If the problem persists, the username may already be taken.';
        }

        setFlash('error', $errorMessage);
        redirect('/profile.php');
    } catch (Exception $e) {
        error_log("Profile update error: " . $e->getMessage());
        if (DEBUG) {
            setFlash('error', $e->getMessage());
        } else {
            setFlash('error', 'Failed to update account. Please try again.');
        }
        redirect('/profile.php');
    }
}

