        // Tab switching functionality
        function switchTab(tabName) {
            // Hide all tab contents
            document.querySelectorAll('.tab-content').forEach(content => {
                content.classList.add('hidden');
            });

            // Remove active styling from all tabs
            document.querySelectorAll('.tab-button').forEach(button => {
                button.classList.remove('border-blue-500', 'bg-blue-50', 'text-blue-700');
                button.classList.add('border-gray-200', 'bg-white', 'text-gray-600');
            });

            // Show selected tab content
            const selectedContent = document.getElementById('tab-content-' + tabName);
            if (selectedContent) {
                selectedContent.classList.remove('hidden');
            }

            // Add active styling to selected tab
            const selectedTab = document.getElementById('tab-' + tabName);
            if (selectedTab) {
                selectedTab.classList.remove('border-gray-200', 'bg-white', 'text-gray-600');
                selectedTab.classList.add('border-blue-500', 'bg-blue-50', 'text-blue-700');
            }
        }

        // Initialize - show main tab or ?tab= query
        document.addEventListener('DOMContentLoaded', function() {
            var match = /[?&]tab=([^&]+)/.exec(window.location.search);
            var tab = match ? match[1] : 'main';
            if (document.getElementById('tab-' + tab)) {
                switchTab(tab);
            } else {
                switchTab('main');
            }
        });

        function updateUsernamePreview(value) {
            const preview = document.getElementById('username-preview');
            if (preview) preview.textContent = value || 'username';
        }

        // Delete account modal
        (function() {
            const modal = document.getElementById('delete-account-modal');
            const openBtn = document.getElementById('open-delete-account-modal');
            const cancelBtn = document.getElementById('cancel-delete-account');
            const confirmBtn = document.getElementById('confirm-delete-account');
            const passwordInput = document.getElementById('delete-account-password');
            const confirmationInput = document.getElementById('delete-account-confirmation');
            const errorBox = document.getElementById('delete-account-error');

            function showError(message) {
                errorBox.textContent = message;
                errorBox.classList.remove('hidden');
            }

            function openModal() {
                passwordInput.value = '';
                confirmationInput.value = '';
                errorBox.classList.add('hidden');
                modal.classList.remove('hidden');
                modal.classList.add('flex');
            }

            function closeModal() {
                modal.classList.add('hidden');
                modal.classList.remove('flex');
            }

            openBtn.addEventListener('click', openModal);
            cancelBtn.addEventListener('click', closeModal);
            modal.addEventListener('click', function(e) {
                if (e.target === modal) closeModal();
            });

            confirmBtn.addEventListener('click', async function() {
                errorBox.classList.add('hidden');
                confirmBtn.disabled = true;
                confirmBtn.textContent = 'Deleting...';
                try {
                    const response = await fetch('/api/account/delete-account.php', {
                        method: 'POST',
                        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
                        body: new URLSearchParams({
                            <?php echo json_encode(CSRF_TOKEN_NAME); ?>: <?php echo json_encode(csrfToken()); ?>,
                            password: passwordInput.value,
                            confirmation: confirmationInput.value,
                        }),
                    });
                    const result = await response.json();
                    if (response.ok && result.success) {
                        window.location.href = '/?account_deleted=1';
                    } else {
                        showError(result.error || 'Something went wrong. Please try again.');
                    }
                } catch (err) {
                    showError('Network error. Please try again.');
                } finally {
                    confirmBtn.disabled = false;
                    confirmBtn.textContent = 'Delete my account';
                }
            });
        })();
    </script>

